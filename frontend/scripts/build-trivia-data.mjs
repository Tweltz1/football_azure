// Writes supabase/functions/_shared/triviaData.ts, the season stat lines the lobby trivia games
// (Price Is Right, Name That Player) ask about. It reads the committed playerInsights.js and
// playerData.js, so run `node scripts/build-trivia-data.mjs` after those change seasons.
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import fs from 'node:fs';

const here = path.dirname(fileURLToPath(import.meta.url));
const dataDir = path.resolve(here, '../src/data');
export const TRIVIA_FILE = path.resolve(here, '../../supabase/functions/_shared/triviaData.ts');

const loadModule = (file) =>
  import(`data:text/javascript;base64,${Buffer.from(fs.readFileSync(path.join(dataDir, file), 'utf8')).toString('base64')}`);

export async function buildTriviaData() {
  const { playerInsightsMeta, playerStatsById } = await loadModule('playerInsights.js');
  const { initialPlayerList } = await loadModule('playerData.js');
  const names = new Map(initialPlayerList.map((p) => [p.id, p.name]));
  const rows = Object.keys(playerStatsById).sort()
    .filter((id) => names.has(id) && playerStatsById[id].games > 0)
    .map((id) => {
      const s = playerStatsById[id];
      const t = s.totals;
      return [names.get(id), s.position, s.team, s.games, Math.round(t.fantasyPointsPpr * 10) / 10,
        t.passingYards, t.passingTds, t.interceptions, t.rushingYards, t.rushingTds, t.receptions, t.receivingYards, t.receivingTds];
    });
  return [
    '// GENERATED by frontend/scripts/build-trivia-data.mjs from playerInsights.js. Do not edit.',
    '// Each row: name, position, NFL team, games, PPR points, pass yds, pass TD, INT, rush yds, rush TD, rec, rec yds, rec TD.',
    '',
    'export type TriviaRow = [string, string, string, number, number, number, number, number, number, number, number, number, number];',
    '',
    `export const TRIVIA_SEASON = ${JSON.stringify(String(playerInsightsMeta.statsSeason))};`,
    '',
    'export const TRIVIA_ROWS: TriviaRow[] = [',
    ...rows.map((row) => `  ${JSON.stringify(row)},`),
    '];',
    '',
  ].join('\n');
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  fs.writeFileSync(TRIVIA_FILE, await buildTriviaData());
  console.log(`Wrote ${path.relative(process.cwd(), TRIVIA_FILE)}`);
}
