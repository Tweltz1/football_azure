// Writes supabase/functions/_shared/triviaData.ts: regular-season stat lines for the best fantasy
// seasons from 1999 on, for the lobby trivia games (Price Is Right, Name That Player). It downloads
// nflverse's season stats, so run it by hand (`node scripts/build-trivia-data.mjs`) once a season ends.
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import fs from 'node:fs';

const here = path.dirname(fileURLToPath(import.meta.url));
export const TRIVIA_FILE = path.resolve(here, '../../supabase/functions/_shared/triviaData.ts');

const RELEASES = 'https://github.com/nflverse/nflverse-data/releases/download';
const ALL_SEASONS = `${RELEASES}/player_stats/player_stats_season.csv`;
const seasonFile = (season) => `${RELEASES}/stats_player/stats_player_reg_${season}.csv`;
/** How many of each position's best seasons to keep per year. */
const KEEP = { QB: 16, RB: 30, WR: 36, TE: 12 };
// Earlier seasons in nflverse are rebuilt from play-by-play with missing games (Warner 1999 is short
// ~400 yards), so they are left out.
const FIRST_SEASON = 2001;

function parseCsv(text) {
  const rows = [];
  let row = [];
  let field = '';
  let quoted = false;
  for (let i = 0; i < text.length; i += 1) {
    const c = text[i];
    if (quoted) {
      if (c === '"' && text[i + 1] === '"') { field += '"'; i += 1; } else if (c === '"') quoted = false; else field += c;
    } else if (c === '"') quoted = true;
    else if (c === ',') { row.push(field); field = ''; } else if (c === '\n') { row.push(field); rows.push(row); row = []; field = ''; } else if (c !== '\r') field += c;
  }
  if (field || row.length) { row.push(field); rows.push(row); }
  const [head, ...body] = rows;
  return body.filter((r) => r.length === head.length).map((r) => Object.fromEntries(head.map((h, i) => [h, r[i]])));
}

const fetchCsv = async (url) => {
  const res = await fetch(url);
  if (!res.ok) throw new Error(`${url}: ${res.status}`);
  return parseCsv(await res.text());
};

// nflverse labels old seasons with today's team codes; show what the team was called then.
const teamThen = (team, season) => {
  if (team === 'LAC' && season < 2017) return 'SD';
  if (team === 'LA' && season < 2016) return 'STL';
  if (team === 'LV' && season < 2020) return 'OAK';
  if (team === 'LA') return 'LAR';
  return team;
};

const num = (v) => (Number.isFinite(Number(v)) ? Number(v) : 0);

export async function buildTriviaData() {
  const all = (await fetchCsv(ALL_SEASONS)).filter((r) => r.season_type === 'REG');
  const lastSeason = Math.max(...all.map((r) => num(r.season)));
  // Newer seasons may only be in the per-season files.
  for (let season = lastSeason + 1; season < lastSeason + 4; season += 1) {
    try {
      (await fetchCsv(seasonFile(season))).forEach((r) => all.push({ ...r, interceptions: r.interceptions ?? r.passing_interceptions }));
    } catch (error) {
      break;
    }
  }
  const rows = [];
  // Only finished seasons (one in progress has nobody past a handful of games).
  const seasons = [...new Set(all.map((r) => num(r.season)))]
    .filter((s) => s >= FIRST_SEASON && all.filter((r) => num(r.season) === s && num(r.games) >= 14).length >= 50)
    .sort();
  for (const season of seasons) {
    for (const [position, keep] of Object.entries(KEEP)) {
      all.filter((r) => num(r.season) === season && r.position === position && num(r.games) >= 6)
        .sort((a, b) => num(b.fantasy_points_ppr) - num(a.fantasy_points_ppr))
        .slice(0, keep)
        .forEach((r) => rows.push([
          r.player_display_name, position, teamThen(r.recent_team, season), season, num(r.games),
          Math.round(num(r.fantasy_points_ppr) * 10) / 10,
          num(r.passing_yards), num(r.passing_tds), num(r.interceptions), num(r.rushing_yards), num(r.rushing_tds),
          num(r.receptions), num(r.receiving_yards), num(r.receiving_tds),
        ]));
    }
  }
  return [
    '// GENERATED by frontend/scripts/build-trivia-data.mjs from nflverse season stats. Do not edit.',
    `// The best regular seasons per position, ${seasons[0]}-${seasons[seasons.length - 1]}.`,
    '// Each row: name, position, team, season, games, PPR points, pass yds, pass TD, INT, rush yds, rush TD, rec, rec yds, rec TD.',
    '',
    'export type TriviaRow = [string, string, string, number, number, number, number, number, number, number, number, number, number, number];',
    '',
    'export const TRIVIA_ROWS: TriviaRow[] = [',
    ...rows.map((row) => `  ${JSON.stringify(row)},`),
    '];',
    '',
  ].join('\n');
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  fs.writeFileSync(TRIVIA_FILE, await buildTriviaData());
  console.log(`Wrote ${path.relative(process.cwd(), TRIVIA_FILE)}`);
}
