/** Picks `count` questions with shuffled answers. rand() returns [0, 1). */
export function pickQuestions(rand, count = 12) {
  const pool = QUESTIONS.map((q, i) => ({ q, i }));
  for (let i = pool.length - 1; i > 0; i -= 1) {
    const j = Math.floor(rand() * (i + 1));
    [pool[i], pool[j]] = [pool[j], pool[i]];
  }
  return pool.slice(0, count).map(({ q }) => {
    const [text, right, ...wrong] = q;
    const answers = [right, ...wrong];
    for (let i = answers.length - 1; i > 0; i -= 1) {
      const j = Math.floor(rand() * (i + 1));
      [answers[i], answers[j]] = [answers[j], answers[i]];
    }
    return { text, answers, correct: answers.indexOf(right) };
  });
}
