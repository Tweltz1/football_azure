// Trains the tech detector: is a customer text a car question ("why does it shake when I brake?")? Writes
// supabase/functions/_shared/smsTechWeights.ts. It only looks at texts the main sorter leaves for staff, so it can
// never change an automatic reply; staff get a "look it up in How-to" shortcut for these.
//   node ml/sms-topics/train-tech.mjs
// Data: real car questions from Mechanics Stack Exchange (CC BY-SA 4.0, credit: mechanics.stackexchange.com users,
// via the flax-sentence-embeddings/stackexchange_title_body_jsonl mirror) and generated customer car questions,
// against generated shop texts and CLINC150 (CC BY 3.0). No shop or customer data.
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { gunzipSync } from 'node:zlib';
import { execFileSync } from 'node:child_process';
import { chattyTexts, clincTexts, mechanicsTexts, mulberry32, shopTexts, techTexts } from './data.mjs';
import { DIM, features } from '../../supabase/functions/_shared/smsTopicModel.ts';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..', '..');
async function cached(name, url, binary) {
  const file = join(here, '.cache', name);
  if (!existsSync(file)) {
    mkdirSync(dirname(file), { recursive: true });
    const res = await fetch(url);
    if (!res.ok) throw new Error(name + ' download failed: ' + res.status);
    writeFileSync(file, Buffer.from(await res.arrayBuffer()));
  }
  return readFileSync(file);
}
const clinc = JSON.parse((await cached('clinc150.json', 'https://raw.githubusercontent.com/clinc/oos-eval/master/data/data_full.json')).toString('utf8'));
const mechLines = gunzipSync(await cached('mechanics.jsonl.gz', 'https://huggingface.co/datasets/flax-sentence-embeddings/stackexchange_title_body_jsonl/resolve/main/mechanics.stackexchange.com.jsonl.gz')).toString('utf8').split('\n');

const rng = mulberry32(20261110);
const shop = shopTexts(rng, 10);
const pos = [...mechanicsTexts(rng, mechLines, Number(process.env.MECH_TEXTS || 8000)), ...techTexts(rng, 30)];
// Shop texts that need a person (prices, comebacks, warranty, scheduling) count three times: they are the look-alikes.
const shopReview = shop.filter((r) => r.topic === 'review');
const neg = [...shop, ...shopReview, ...shopReview, ...chattyTexts(rng, shop, 3000), ...clincTexts(clinc).filter((_, i) => i % 2 === 0)];
// Real rows staff or a person labeled tech (LEARN_ROWS from the weekly retrain), never printed.
const real = process.env.LEARN_ROWS && existsSync(process.env.LEARN_ROWS) ? JSON.parse(readFileSync(process.env.LEARN_ROWS, 'utf8')).filter((r) => r.label) : [];
for (const r of real) (r.label === 'tech' ? pos : neg).push({ text: r.text });
const rows = [...pos.map((r) => ({ f: features(r.text), y: 1 })), ...neg.map((r) => ({ f: features(r.text), y: 0 }))];
console.log('tech detector texts', rows.length, 'car questions', pos.length, 'other', neg.length);
const cw = [rows.length / (2 * neg.length), rows.length / (2 * pos.length)];

const K = 2, w = new Float64Array(DIM * K), g2 = new Float64Array(DIM * K).fill(1e-6), lr = 0.25, l2 = 2e-6;
for (let epoch = 0; epoch < 10; epoch++) {
  for (let i = rows.length - 1; i > 0; i--) { const j = Math.floor(rng() * (i + 1)); [rows[i], rows[j]] = [rows[j], rows[i]]; }
  for (const { f, y } of rows) {
    const z = [0, 0];
    for (const i of f) { z[0] += w[i * K]; z[1] += w[i * K + 1]; }
    const m = Math.max(...z), e = z.map((v) => Math.exp(v - m)), sum = e[0] + e[1];
    for (let k = 0; k < K; k++) {
      const grad = (e[k] / sum - (k === y ? 1 : 0)) * cw[y];
      for (const i of f) { const at = i * K + k, gr = grad + l2 * w[at]; g2[at] += gr * gr; w[at] -= lr * gr / Math.sqrt(g2[at]); }
    }
  }
}
let max = 0; for (const v of w) max = Math.max(max, Math.abs(v));
const scale = max / 127, q = Buffer.alloc(w.length);
for (let i = 0; i < w.length; i++) q.writeInt8(Math.max(-127, Math.min(127, Math.round(w[i] / scale))), i);
writeFileSync(join(root, 'supabase/functions/_shared/smsTechWeights.ts'),
  '// Generated by ml/sms-topics/train-tech.mjs on ' + new Date().toISOString().slice(0, 10) + '. Do not edit by hand.\n' +
  '// Trained on Mechanics Stack Exchange questions (CC BY-SA 4.0), generated shop texts and CLINC150 (CC BY 3.0).\n' +
  'export const TECH_WEIGHTS = { scale: ' + scale + ', data: \'' + q.toString('base64') + '\' };\n');
execFileSync(process.execPath, [join(here, 'eval.mjs')], { stdio: 'inherit' });
