// Trains the customer text sorter and writes supabase/functions/_shared/smsTopicWeights.ts.
//   node ml/sms-topics/train.mjs            (downloads CLINC150 once into ml/sms-topics/.cache)
// Then: node --test supabase/tests/smsTopicModel.test.ts
//
// Model: softmax regression on hashed features (see features() in smsTopicModel.ts), trained with AdaGrad,
// stored as 8-bit weights. It is small (about 110 KB), runs in well under a millisecond, and costs nothing per text.
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { clincTexts, mulberry32, shopTexts } from './data.mjs';
import { DIM, TOPICS, features } from '../../supabase/functions/_shared/smsTopicModel.ts';
import { execFileSync } from 'node:child_process';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..', '..');
const cache = join(here, '.cache', 'clinc150.json');
if (!existsSync(cache)) {
  mkdirSync(dirname(cache), { recursive: true });
  const res = await fetch('https://raw.githubusercontent.com/clinc/oos-eval/master/data/data_full.json');
  if (!res.ok) throw new Error('CLINC150 download failed: ' + res.status);
  writeFileSync(cache, await res.text());
}
const clinc = JSON.parse(readFileSync(cache, 'utf8'));

const rng = mulberry32(20261109);
const shop = shopTexts(rng, 14);
// Every 3rd CLINC text is enough variety without drowning the shop texts.
const general = clincTexts(clinc).filter((_, i) => i % 3 === 0);
const rows = [...shop, ...general].map((r) => ({ f: features(r.text), y: TOPICS.indexOf(r.topic) }));
const counts = TOPICS.map((_, k) => rows.filter((r) => r.y === k).length);
console.log('training texts', rows.length, Object.fromEntries(TOPICS.map((t, k) => [t, counts[k]])));
const classWeight = counts.map((c) => rows.length / (TOPICS.length * c));

const K = TOPICS.length;
const w = new Float64Array(DIM * K), g2 = new Float64Array(DIM * K).fill(1e-6);
const lr = 0.25, l2 = 2e-6;
for (let epoch = 0; epoch < 12; epoch++) {
  for (let i = rows.length - 1; i > 0; i--) { const j = Math.floor(rng() * (i + 1)); [rows[i], rows[j]] = [rows[j], rows[i]]; }
  let loss = 0;
  for (const { f, y } of rows) {
    const z = new Float64Array(K);
    for (const i of f) for (let k = 0; k < K; k++) z[k] += w[i * K + k];
    const m = Math.max(...z); let sum = 0;
    for (let k = 0; k < K; k++) { z[k] = Math.exp(z[k] - m); sum += z[k]; }
    loss -= Math.log(z[y] / sum) * classWeight[y];
    for (let k = 0; k < K; k++) {
      const grad = (z[k] / sum - (k === y ? 1 : 0)) * classWeight[y];
      for (const i of f) {
        const at = i * K + k, gr = grad + l2 * w[at];
        g2[at] += gr * gr; w[at] -= lr * gr / Math.sqrt(g2[at]);
      }
    }
  }
  console.log('epoch', epoch + 1, 'loss', (loss / rows.length).toFixed(4));
}

// 8-bit weights: one scale for the whole table.
let max = 0; for (const v of w) max = Math.max(max, Math.abs(v));
const scale = max / 127;
const q = Buffer.alloc(w.length);
for (let i = 0; i < w.length; i++) q.writeInt8(Math.max(-127, Math.min(127, Math.round(w[i] / scale))), i);
writeFileSync(join(root, 'supabase/functions/_shared/smsTopicWeights.ts'),
  '// Generated by ml/sms-topics/train.mjs on ' + new Date().toISOString().slice(0, 10) + '. Do not edit by hand.\n' +
  '// Trained on generated shop texts plus CLINC150 (Larson et al. 2019, CC BY 3.0). No shop or customer data.\n' +
  'export const WEIGHTS = { scale: ' + scale + ', data: \'' + q.toString('base64') + '\' };\n');

// Score in a fresh process so the new weights load.
execFileSync(process.execPath, [join(here, 'eval.mjs')], { stdio: 'inherit' });
